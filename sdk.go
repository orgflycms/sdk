// Package sdk — контракт между ядром flycms и плагином.
//
// Плагин — папка с Go-файлами одного пакета, где есть функция
//
//	func Init(api sdk.API) error
//
// Папка называется полным именем плагина «пространство.имя» (studio.promo):
// пространство имён партнёр выбирает в кабинете, оно — префикс его плагинов.
// Пакет внутри назван коротким именем (package promo).
//
// Ядро читает папку интерпретатором Yaegi при старте и по кнопке «Перечитать»
// в разделе «Плагины», вызывает Init один раз и дальше зовёт то, что плагин
// зарегистрировал: обработчики адресов, перехватчики корзины, обработчики
// оплаты и доставки, открытые адреса и подписчики событий заказов.
// Компилировать ничего не нужно: положили папку — плагин работает.
//
// Плагину доступны этот пакет и часть стандартной библиотеки Go: список и
// запреты (файлы, процессы, сокеты) — в README.md. Сторонних модулей внутри
// плагина нет: их некому скачать и собрать.
//
// Горутины и отложенные вызовы (go, time.AfterFunc, context.AfterFunc,
// sync.WaitGroup) разрешены, и это единственное слабое место: паника в
// горутине, которую запустил плагин, не проходит через перехват ядра и
// останавливает весь магазин. Первая строка каждой своей горутины и функции,
// отданной в AfterFunc, — defer с recover(). Ядро само перехватывает панику
// только в литерале `go func() {...}()`, в AfterFunc и WaitGroup.Go; в
// `go f(x)` с именованной функцией или методом — нет.
package sdk

import (
	"context"
	"html/template"
	"math"
	"net/http"
	"time"
)

// API — то, что ядро даёт плагину в Init. Всё зарегистрированное живёт до
// следующего перечитывания плагинов.
type API interface {
	// Name — полное имя плагина «пространство.имя», оно же имя папки.
	Name() string

	// DB — база магазина от имени роли плагина. Свои таблицы плагин заводит
	// сам в Init («create table if not exists codes …»): они ложатся в его
	// собственную схему, префикс в имени больше не нужен. Данные магазина
	// видны только по правам из plugin.json («access»), которые владелец
	// включил на странице плагина; настройки магазина, пароли, сессии и
	// ключи способов оплаты не видны никогда. Право выключено — запрос
	// возвращает ошибку, магазин работает. Права и таблицы за ними — README.
	DB() DB

	// Menu добавляет пункт в меню админки. href — адрес внутри плагина,
	// от «/»: Menu("Промокоды", "/") ведёт на GET /{$} плагина.
	Menu(label, href string)

	// Handle регистрирует обработчик по шаблону http.ServeMux: «GET /{$}»,
	// «POST /new», «POST /{id}/delete». Адреса плагина живут под
	// /admin/x/<имя>/ и открыты только вошедшему в админку.
	Handle(pattern string, h http.HandlerFunc)

	// Path — полный адрес маршрута плагина для ссылок и форм: Path("/new")
	// → «/admin/x/studio.promo/new».
	Path(href string) string

	// Page рисует страницу плагина в обёртке админки: меню, шапка, подвал.
	// body — готовая разметка; собирать её удобно html/template из stdlib.
	Page(w http.ResponseWriter, r *http.Request, title string, body template.HTML)

	// OnCart подписывает перехватчик корзины. Ядро зовёт его всякий раз,
	// когда считает корзину — на странице корзины и при оформлении заказа.
	// Перехватчик правит Discount и Notes, остальное только читает.
	OnCart(fn func(ctx context.Context, c *Cart))

	// Money — копейки в строку для покупателя: 123456 → «1 234,56 ₽».
	Money(kopecks int64) string

	// RegisterPayment добавляет обработчик оплаты. В админке он появляется
	// в списке «Обработчик» способа оплаты как «<плагин>/<code>»
	// (flycms.tbank/card): владелец заводит способ, выбирает обработчик и
	// заполняет вкладку «Настройки» полями h.Settings. Обработчиков у
	// плагина может быть несколько. code — [a-z][a-z0-9_]{0,31}, в плагине
	// не повторяется. Без Title или Start, с повтором кода или неверным
	// полем настроек плагин не загружается — ошибка видна в «Плагинах».
	//
	// Деньги считает ядро. Обработчик сообщает, что ответил провайдер
	// (PayEvent), а статус оплаты и заказа ядро меняет само — после сверки
	// суммы и только вперёд: оплаченное не становится неоплаченным.
	RegisterPayment(code string, h PaymentHandler)

	// PDF собирает документ A4 из абзацев и таблиц шрифтом ядра с
	// кириллицей — для счетов, актов, накладных. Ошибка — неверная таблица,
	// больше 100 страниц или больше 1 МиБ текста.
	PDF(doc Doc) ([]byte, error)

	// License — ключ этого плагина в магазине (платный плагин из
	// маркетплейса): ядро проверило подпись без сети и сверило домен.
	// Плагин без ключа работает всегда — что ограничить без ключа,
	// решает автор. Плагин видит только свой ключ. Метод появился позже
	// остальных: на старом ядре плагин, который его зовёт, не загрузится.
	License() PluginLicense

	// RegisterDelivery добавляет обработчик доставки. В админке он
	// появляется в списке «Обработчик» способа доставки как
	// «<плагин>/<code>» (studio.cdek/door): владелец заводит способ (или
	// профиль службы), выбирает обработчик и заполняет вкладку «Настройки»
	// полями h.Settings. Правила code, Title и полей — как у
	// RegisterPayment; без Quote плагин не загружается.
	//
	// Цену считает обработчик, а в заказ её пишет ядро: поверх ответа
	// действуют «Бесплатно от» и ограничения способа. Метод появился в
	// v0.4.0: на старом ядре плагин, который его зовёт, не загрузится.
	RegisterDelivery(code string, h DeliveryHandler)

	// HandlePublic регистрирует открытый адрес: без входа в админку, под
	// /x/<имя>/ — для обмена с 1С, вебхуков CRM, фидов маркетплейсов.
	// Шаблон — как у Handle. Проверка (пароль, подпись, Basic) — дело
	// плагина: ядро пускает всех. Куки в запрос не приходят и из ответа
	// выбрасываются; тело — не больше 8 МиБ (ядро читает его до
	// обработчика); 120 запросов в минуту с адреса и 4 одновременно;
	// контекст — 60 с; изменяющий запрос со страницы чужого сайта — 403;
	// ответ — текст, JSON, XML, CSV, PDF или картинка, но не HTML, без
	// перенаправлений. Появился в v0.4.0.
	HandlePublic(pattern string, h http.HandlerFunc)

	// PublicURL — полный адрес открытого маршрута, чтобы показать его
	// владельцу: PublicURL("/exchange") →
	// «https://shop.ru/x/studio.onec/exchange». Пока в настройках магазина
	// не задан «Адрес магазина» — только путь. Появился в v0.4.0.
	PublicURL(href string) string

	// Catalog — запись в каталог через ядро: товары, предложения, цены,
	// остатки по внешнему коду. Нужна группа catalog:write в plugin.json и
	// согласие владельца; без них каждый метод возвращает ошибку. Пересчёт
	// цен и остатков держит ядро. Количество товаров не ограничено;
	// работа магазина требует действующей лицензии. Появился в v0.4.0.
	Catalog() Catalog

	// OnOrder подписывает плагин на события заказов: создан, сменился
	// статус, оплачен полностью. Ядро доставляет каждое событие хотя бы раз
	// и по порядку номеров: ошибка, паника или 15 с без ответа — повтор
	// того же события позже (через минуту, потом реже, до трёх суток).
	// Повтор приходит с тем же OrderEvent.ID — обработчик должен быть
	// готов к нему. Вызовы идут по одному: следующий — только когда
	// прошлый вернулся, даже если он пережил свой срок. Событие, на котором
	// плагин ошибается трое суток, пропускается — это видно на странице
	// плагина. Нужна группа orders:read в plugin.json, иначе плагин не
	// загрузится; владелец выключил её — события ждут, пока не включит.
	// Появился в v0.4.0.
	OnOrder(fn func(ctx context.Context, e *OrderEvent) error)

	// Mail отправляет письмо через почту магазина (SMTP из его настроек),
	// от его отправителя. Получатель — один адрес: владелец (почта для
	// заказов или контакт магазина) или покупатель — адрес из заказа или
	// учётной записи этого магазина. Чужой адрес — ошибка: почта магазина
	// не рассылает по спискам плагина. Тема — одна строка до 200 знаков,
	// html — тело письма как есть (вёрстка — дело плагина), до 256 КиБ. Не
	// больше 100 писем в час на плагин. Каждое письмо — строка в журнале
	// плагина и магазина: кому и тема. Ошибка — почта не настроена, лимит,
	// адрес не подходит, SMTP не принял; текст — для владельца. Контекст —
	// не дольше 10 с. Появился в v0.5.0.
	Mail(ctx context.Context, to, subject, html string) error

	// RegisterSettings объявляет настройки самого плагина — не способа
	// оплаты или доставки, а общие: ключ сервиса, адрес для отчётов.
	// Владелец заполняет их на странице плагина в «Плагинах»; поля — как у
	// PaymentHandler.Settings, секрет (password) в форму не выводится.
	// Зовётся в Init один раз; неверное поле или повторный вызов — плагин
	// не загружается. Появился в v0.5.0.
	RegisterSettings(fields []Field)

	// Setting — значение настройки плагина сейчас; пусто — не задано или
	// такого поля плагин не объявлял. Владелец сохранил форму — следующий
	// вызов видит новое значение, «Перечитать» не нужен. Появился в v0.5.0.
	Setting(key string) string

	// Log пишет строку в журнал плагина: его видно на странице плагина в
	// «Плагинах» (последние 100 строк, до перезапуска магазина) и в журнале
	// службы магазина с именем плагина. Строка обрезается до 1000 знаков;
	// больше 60 строк в минуту не пишется — журнал отмечает, сколько
	// пропущено. Секреты сюда не пишите: журнал читает владелец. Появился в
	// v0.5.0.
	Log(msg string)
}

// Статусы ключа плагина — PluginLicense.Status.
const (
	LicenseNone        = "none"         // ключа нет
	LicenseValid       = "valid"        // подпись верна, домен магазина тот же
	LicenseWrongDomain = "wrong_domain" // ключ выпущен для другого домена
	LicenseBroken      = "broken"       // не разбирается или подпись не сходится
)

// PluginLicense — ключ плагина, как его видит ядро. «Обновления закончились»
// — не статус: ключ действует, просто новые версии после UpdatesUntil сайт
// по нему не отдаёт.
type PluginLicense struct {
	Status       string    // LicenseNone, LicenseValid, LicenseWrongDomain или LicenseBroken
	Domain       string    // домен из ключа; пусто у none и broken
	UpdatesUntil time.Time // до какого дня выдаются обновления; ноль у none и broken
	Key          string    // сам ключ — для сервера автора; пусто у none и broken
}

// PaymentHandler — обработчик оплаты. Функции зовутся параллельно — из
// запросов покупателей, уведомлений провайдера и фоновой задачи ядра.
// Паника стоит одного вызова, не магазина. Контекст ограничен по времени
// (Start — 20 с, Notify — 10 с, Check — 15 с): передавайте его в
// http.NewRequestWithContext.
type PaymentHandler struct {
	// Title — название в списке обработчиков админки: «Т-Банк: карта и СБП».
	Title string
	// Button — надпись кнопки на странице заказа, в письме и в кабинете:
	// «Оплатить картой», «Скачать счёт». Пусто — «Оплатить».
	Button string
	// Settings — поля вкладки «Настройки» способа оплаты. Значения приходят
	// в Payment.Settings и Notice.Settings — только этому обработчику и
	// только того способа, к которому относится оплата.
	Settings []Field

	// Start — покупатель нажал кнопку или открыл ссылку из письма.
	// Обязателен. Ядро зовёт его для любой неотменённой оплаты, в том числе
	// оплаченной: счёт нужен и после оплаты, а карточному обработчику на
	// оплаченную достаточно вернуть пустой PayStart.
	//
	// Ошибка показывается покупателю как есть — пишите её для покупателя.
	// Если вместе с ошибкой заполнен PayStart.ExternalID, ядро его всё
	// равно запоминает: платёж у провайдера уже создан, повторный Start не
	// должен создать второй.
	Start func(ctx context.Context, p *Payment) (PayStart, error)

	// Notify — уведомление провайдера на Payment.NotifyURL. nil — способ
	// без уведомлений. Подпись проверяет обработчик: без проверки любой
	// посторонний отметит заказ оплаченным. Ошибка — ядро отвечает 400 и
	// ничего не меняет.
	Notify func(ctx context.Context, n *Notice) (PayEvent, error)

	// Check — спросить провайдера о статусе. nil — не спрашивать. Ядро
	// зовёт его само для неоплаченных оплат с ExternalID: первый час — раз
	// в 5 минут, первые сутки — раз в час, потом — раз в 6 часов, не
	// дольше 30 дней; а ещё когда покупатель вернулся на страницу заказа и
	// по кнопке владельца «Проверить оплату».
	Check func(ctx context.Context, p *Payment) (PayEvent, error)

	// Validate — проверить настройки способа, когда владелец сохраняет
	// вкладку «Настройки» или заводит способ: формат ключа, связь с
	// провайдером. settings — какими настройки станут после сохранения,
	// секреты тоже. Ошибка показывается владельцу над формой как есть, и
	// ничего не сохраняется. nil — без проверки. Контекст — 10 с. Поле
	// появилось в v0.5.0.
	Validate func(ctx context.Context, settings map[string]string) error
}

// Field — поле формы настроек способа.
type Field struct {
	Key   string // ключ в настройках: terminal_key; [a-z][a-z0-9_]{0,31}
	Label string // «Ключ терминала»
	Hint  string // подсказка под полем
	// Kind — "" (строка), "number", "textarea", "select" (один из Options)
	// или "password": секрет в форме не показывается, пустое поле при
	// сохранении значения не меняет.
	Kind    string
	Options []string // варианты для "select"; значение и подпись совпадают
	// Required — пока поле пусто, покупатель способ не видит, а владелец
	// видит предупреждение на вкладке «Настройки».
	Required bool
}

// Статусы в Payment.Status и PayEvent.Status.
const (
	PayPending = "pending" // ждёт оплаты; в PayEvent — «не меняй статус, запомни ExternalStatus»
	PayPaid    = "paid"    // деньги пришли
	PayFailed  = "failed"  // попытка не удалась; покупатель может нажать кнопку ещё раз
)

// Payment — оплата заказа глазами обработчика. Суммы — в копейках.
type Payment struct {
	ID      int64     // номер оплаты в магазине: уникален, годится в номер заказа у провайдера
	OrderID int64     // номер заказа, который видит покупатель
	Amount  int64     // к оплате
	Status  string    // PayPending, PayPaid или PayFailed
	Created time.Time // когда оформлен заказ, в поясе магазина (Москва, UTC+3 — тот же, что у дат админки): дата счёта

	// Что вернул прошлый Start и что сообщил провайдер в последний раз.
	// Пусто — платежа у провайдера ещё нет.
	ExternalID     string
	ExternalURL    string
	ExternalStatus string

	Items []PayItem // строки заказа и доставка; сумма Sum по строкам равна Amount
	Payer Payer

	Settings map[string]string // настройки способа, секреты тоже

	ReturnURL string // страница заказа: сюда провайдер возвращает покупателя
	NotifyURL string // адрес уведомлений этого способа; пусто, если Notify == nil
}

// PayItem — строка для чека и счёта.
type PayItem struct {
	Name     string  // «Костюм рабочий (52-54)»; у доставки — название способа
	Unit     string  // «шт», «кг»; у доставки пусто
	Qty      float64 // количество в единицах товара
	Price    int64   // цена за единицу до скидки
	Sum      int64   // стоимость строки со скидкой: доля скидки заказа уже вычтена
	Delivery bool    // строка доставки — в чеке это услуга
}

// Payer — кто платит: поля формы оформления по их ролям. У физлица
// Company, INN и KPP пусты.
type Payer struct {
	Type    string // код типа плательщика: individual, company — как заведено в магазине
	Name    string // контактное лицо
	Email   string
	Phone   string
	Company string
	INN     string
	KPP     string
	Address string
	// Values — все поля формы заказа по коду поля, текстом, как их видит
	// покупатель: legal_address → «620000, Екатеринбург, …».
	Values map[string]string
}

// PayStart — ответ Start.
type PayStart struct {
	// ExternalID — номер платежа у провайдера. По нему ядро находит оплату,
	// когда приходит уведомление. Пусто — прежний остаётся.
	ExternalID string
	// URL — адрес у провайдера: платёжная форма, PDF счёта. Ядро запоминает
	// его (Payment.ExternalURL) и, если File пуст, ведёт туда покупателя.
	// Пусты и URL, и File — покупатель возвращается на страницу заказа.
	URL string
	// File — отдать покупателю файл вместо перехода. Пока только PDF.
	File *File
}

type File struct {
	Name string // «Счёт 123.pdf»
	Data []byte
}

// Notice — уведомление провайдера, как его принял магазин.
type Notice struct {
	Body     []byte            // тело запроса, не больше 64 КиБ
	Settings map[string]string // настройки способа, на адрес которого пришло уведомление
}

// PayEvent — что сообщил провайдер. Ядро находит оплату этого способа по
// ExternalID (в Check — по самой оплате), сверяет сумму и меняет статус.
// Повтор того же события ничего не меняет.
type PayEvent struct {
	ExternalID string // номер платежа у провайдера; в Check можно не заполнять
	Status     string // PayPaid, PayFailed или PayPending
	// Amount — сколько подтвердил провайдер. Для PayPaid обязателен и
	// должен совпасть с Payment.Amount, иначе оплата не отмечается.
	Amount         int64
	ExternalStatus string // слово провайдера для карточки заказа: CONFIRMED
	// Reply — тело ответа провайдеру на уведомление: Т-Банк ждёт «OK».
	// Пусто — 200 без тела. В Check не используется.
	Reply string
}

// Doc — документ для API.PDF: A4 книжный, поля 15 мм, шрифт ядра с
// кириллицей (обычный и полужирный). Блоки идут сверху вниз с отступом
// 2 мм и сами переносятся на следующую страницу.
type Doc struct {
	Title  string // название в свойствах файла: «Счёт на оплату № 123»
	Blocks []Block
}

// Block — абзац или таблица: заполнена Table — рисуется она, иначе Text.
type Block struct {
	Text  string  // абзац; длинные строки переносятся по словам, \n — новая строка, "" — пустая строка
	Size  float64 // кегль, пт; 0 — 10. У таблицы — кегль всех её ячеек
	Bold  bool
	Align string // "" — влево, "center", "right"
	Table *Table
}

// Table — таблица на всю ширину страницы. Высота строки — по самой длинной
// ячейке; строка не разрывается, а целиком уходит на новую страницу.
type Table struct {
	Widths []float64 // доли ширины колонок: {1, 10, 2, 2, 3, 3}
	Rows   [][]Cell
	Grid   bool // рамка вокруг каждой ячейки; false — без рамок (подписи)
}

type Cell struct {
	Text  string
	Bold  bool
	Align string // "" — влево, "center", "right"
	Span  int    // сколько колонок занимает; 0 — одну
}

// DB — доступ к базе без database/sql: строки приходят готовыми картами.
// Плейсхолдеры — $1, $2, как в Postgres.
type DB interface {
	Exec(ctx context.Context, query string, args ...any) error
	Query(ctx context.Context, query string, args ...any) ([]map[string]any, error)
}

// Cart — корзина покупателя на входе в перехватчик. Суммы в копейках.
type Cart struct {
	Items    []CartItem
	Code     string   // промокод, который ввёл покупатель; пусто — не вводил
	Subtotal int64    // сумма товаров до скидок
	Discount int64    // скидка: перехватчики прибавляют сюда
	Notes    []string // пояснения покупателю: «Промокод SALE10: −1 000 ₽»

	// Кто покупает и что выбрал на форме оформления — только для чтения:
	// правку перехватчика ядро не сохраняет. 0 — гость, способ ещё не
	// выбран или корзину считают не на оформлении (страница корзины,
	// корзины в админке — там только CustomerID). Поля появились в v0.5.0.
	CustomerID     int64 // покупатель с учётной записью
	PaymentMethod  int64 // способ оплаты — номер в магазине, как OrderPayment.MethodID
	DeliveryMethod int64 // способ доставки (профиль), как OrderDelivery.MethodID
}

type CartItem struct {
	ProductID int64
	OfferID   int64  // торговое предложение (SKU) товара ProductID: размер, цвет
	Name      string // «Футболка (TS-M)» — у товара с одним предложением просто название
	Price     int64
	Qty       float64 // штуки, килограммы, метры — по единице товара; шаг задаёт магазин

	// Discount — часть скидки, отнесённая перехватчиком на эту строку: ядро
	// запоминает её в заказе рядом со строкой. Общую скидку корзины
	// перехватчик по-прежнему прибавляет в Cart.Discount — считает он, ядро
	// только сохраняет разбивку.
	Discount int64
}

// Sum — стоимость строки в копейках, округлённая до копейки: 0,3 м × 990 ₽ = 297 ₽.
func (i CartItem) Sum() int64 { return int64(math.Round(float64(i.Price) * i.Qty)) }

// Total — к оплате. Ниже нуля не бывает: два щедрых плагина не сделают
// магазин должником.
func (c *Cart) Total() int64 {
	if c.Discount >= c.Subtotal {
		return 0
	}
	return c.Subtotal - c.Discount
}

// DeliveryHandler — обработчик доставки: СДЭК, Почта России. Quote зовётся
// параллельно из расчётов оформления разных покупателей. Паника стоит
// одного вызова: способ просто не показывается.
type DeliveryHandler struct {
	// Title — название в списке обработчиков админки: «СДЭК: до двери».
	Title string
	// Settings — поля вкладки «Настройки» способа доставки. У профиля
	// службы значения берутся от службы, поверх — свои у профиля; от службы
	// — только если её обработчик того же плагина: чужие ключи плагин не
	// получает.
	Settings []Field

	// Quote — цена и срок для корзины покупателя. Обязателен. Контекст —
	// 5 с: дольше покупатель форму не ждёт. Ядро запоминает ответ на
	// 10 минут для тех же строк, суммы, места, адреса и настроек, ошибку —
	// на минуту: пересчёт формы не идёт к перевозчику каждый раз.
	//
	// Ошибка — способ не показывается, текст уходит в журнал магазина,
	// покупатель его не видит. Цены ещё нет (не указан город) — верните
	// DeliveryQuote.Missing. Ответ вне границ DeliveryQuote — тоже ошибка.
	//
	// Заказ получает цену, которую покупатель видел на форме: изменилась
	// она к подтверждению — ядро показывает новую и просит подтвердить ещё
	// раз.
	Quote func(ctx context.Context, r *DeliveryRequest) (DeliveryQuote, error)

	// Validate — проверка настроек при сохранении, как у
	// PaymentHandler.Validate. У профиля службы settings — настройки
	// службы, поверх — профиля, как их получит Quote. Поле появилось в
	// v0.5.0.
	Validate func(ctx context.Context, settings map[string]string) error
}

// DeliveryRequest — что известно о заказе на форме оформления. Суммы — в
// копейках, вес — в граммах, размеры — в миллиметрах.
type DeliveryRequest struct {
	MethodID  int64             // способ доставки (профиль) в магазине
	Settings  map[string]string // настройки способа, секреты тоже
	Items     []DeliveryItem
	Goods     int64  // сумма товаров со скидкой — объявленная ценность
	WeightG   int    // вес всей корзины; товары без веса — нулём
	PayerType string // код типа плательщика: individual, company

	Place       Place  // местоположение из формы; ID 0 — не выбрано
	Zip         string // поле с ролью «Индекс»
	Address     string // поле с ролью «Адрес»: улица, дом, квартира
	PickupPoint string // поле с ролью «Пункт выдачи»: код или адрес пункта
}

// DeliveryItem — строка корзины для расчёта. Вес и размеры — одной единицы
// товара; 0 — магазин их не указал.
type DeliveryItem struct {
	ProductID, OfferID          int64
	Name                        string
	Qty                         float64
	Price                       int64 // за единицу до скидки
	WeightG                     int
	LengthMM, WidthMM, HeightMM int
}

// Place — местоположение из справочника магазина.
type Place struct {
	ID   int64
	Name string   // «Екатеринбург»
	Path []string // от страны: «Россия», «Свердловская область», «Екатеринбург»
	Code string   // внешний код, как его завёл магазин: ФИАС, КЛАДР, ISO; бывает пустым
}

// DeliveryQuote — ответ Quote.
type DeliveryQuote struct {
	// Price — цена для покупателя до «Бесплатно от» способа: от 0 до
	// 1 000 000 000 копеек (10 млн ₽).
	Price int64
	// MinDays, MaxDays — срок в днях, от 0 до 365, MinDays не больше
	// MaxDays; оба 0 — срок из настроек способа, только MinDays — «от N дн.».
	MinDays, MaxDays int
	// Missing — цены пока нет: «Укажите город». Способ показан с этим
	// текстом вместо цены, оформить заказ с ним нельзя. Price тогда не
	// смотрится.
	Missing string
}

// Catalog — запись в каталог от имени плагина (API.Catalog). Внешний код —
// GUID 1С, id МойСклад: у товара это «Ключ товара» импорта CSV, так что
// файл и плагин правят одни и те же товары. Каждый вызов — своя
// транзакция; ошибка ничего не меняет.
type Catalog interface {
	// Product — товар по внешнему коду; ok=false — такого нет.
	Product(ctx context.Context, external string) (p CatalogProduct, ok bool, err error)
	// SaveProduct создаёт или обновляет товар по p.External и возвращает
	// его номер. Количество товаров не ограничено.
	// Предложений не заводит: товар без них не
	// продаётся.
	SaveProduct(ctx context.Context, p CatalogProduct) (int64, error)
	// SaveOffer создаёт или обновляет предложение по o.External у товара
	// o.Product. Первое предложение товара становится основным; пустой
	// артикул — SKU-<номер>. У комплекта — ошибка.
	SaveOffer(ctx context.Context, o CatalogOffer) (int64, error)
	// SetPrice — цена и зачёркнутая цена предложения, копейки; old 0 —
	// без зачёркнутой. У комплекта цену считает магазин — ошибка.
	SetPrice(ctx context.Context, offer string, price, old int64) error
	// SetStock — сколько физически лежит на складе по умолчанию; остатки
	// других складов не меняются, общий остаток — их сумма с qty. Резервы
	// заказов магазин вычтет сам, ниже резерва этого склада — ошибка.
	// Предложение без остатков по складам — qty и есть весь остаток. У
	// комплекта остаток считает магазин — ошибка.
	SetStock(ctx context.Context, offer string, qty float64) error
}

// CatalogProduct — товар. SaveProduct пишет все поля, кроме ID.
type CatalogProduct struct {
	ID          int64  // номер в магазине; в SaveProduct не читается
	External    string // внешний код, обязателен, до 200 знаков
	Name        string // обязательно
	Section     string // путь раздела «Одежда/Футболки»: недостающие разделы заводятся; пусто — без раздела
	Unit        string // «шт», «кг» — как в справочнике единиц; пусто — штуки
	Description string // HTML описания, как в форме товара
	Active      bool
}

// CatalogOffer — предложение (размер, цвет) товара. SaveOffer пишет все поля.
type CatalogOffer struct {
	Product                     string // внешний код товара
	External                    string // внешний код предложения, обязателен; у 1С — «товар#характеристика»
	SKU                         string // артикул
	Barcode                     string
	Price                       int64 // копейки
	OldPrice                    int64
	WeightG                     int
	LengthMM, WidthMM, HeightMM int
	Active                      bool
}

// Виды событий заказа — OrderEvent.Kind.
const (
	OrderCreated = "created" // заказ оформлен
	OrderStatus  = "status"  // сменился статус: Status, PrevStatus
	OrderPaid    = "paid"    // оплачен полностью; у заказа на 0 ₽ не бывает
)

// OrderEvent — событие заказа для OnOrder.
type OrderEvent struct {
	ID         int64     // номер события: растёт; повтор приходит с тем же
	Kind       string    // OrderCreated, OrderStatus или OrderPaid
	Status     string    // статус после события: new, paid, done, cancelled или свой код магазина
	PrevStatus string    // у OrderStatus — прежний; иначе пусто
	At         time.Time // когда случилось, в поясе дат админки
	// Order — заказ, каким он стал к моменту доставки события: если с тех
	// пор статус сменился ещё раз, Order.Status уже новый, а Status события
	// — тот, что был.
	Order Order
}

// Order — заказ глазами плагина. Суммы — в копейках.
type Order struct {
	ID                                                  int64
	Status                                              string
	Created                                             time.Time // в поясе дат админки
	CustomerID                                          int64     // 0 — гость
	PayerType                                           string
	Customer                                            string // контакты из формы заказа
	Phone                                               string
	Email                                               string
	Subtotal, Discount, DeliveryTotal, Total, PaidTotal int64
	PromoCode, Note                                     string
	// Values — все поля формы заказа по коду поля, текстом, как у Payer.Values.
	Values map[string]string
	// Fields — те же поля снимком оформления, по порядку формы: код, роль и
	// сырое значение. Коды полей у каждого магазина свои — что поле значит,
	// говорит Role. Поле удалили после заказа — его ответ остался здесь.
	Fields []OrderField
	// Items — строки в порядке заказа. Комплект — строка с ценой и под ней
	// строки состава с ParentID и нулевыми суммами: деньги — у строк с
	// ParentID 0, вес и размеры — у строк, у которых нет своих вложенных.
	Items    []OrderItem
	Delivery OrderDelivery
	Payment  OrderPayment
}

// OrderField — ответ покупателя на поле формы заказа, снимком оформления.
type OrderField struct {
	Code  string // код поля в магазине
	Name  string // подпись поля
	Role  string // name, phone, email, location, zip, address, pickup_point, comment, company, inn, kpp; пусто — без роли
	Value string // сырое: номер варианта, номер местоположения, дата ISO
	Text  string // как видит покупатель
}

// OrderItem — строка заказа снимком оформления: название, цена, вес и
// размеры одной единицы, внешние коды — какими были при покупке, даже если
// товар потом изменили или удалили (тогда ProductID и OfferID — 0).
type OrderItem struct {
	ID                          int64 // номер строки заказа
	ParentID                    int64 // строка комплекта, в который входит эта; 0 — своя строка
	ProductID, OfferID          int64
	ProductExternal             string // внешний код товара (CatalogProduct.External); бывает пустым
	OfferExternal               string // внешний код предложения (CatalogOffer.External); бывает пустым
	Name, Article, Unit         string
	Qty                         float64
	Price, Discount, Sum        int64
	WeightG                     int
	LengthMM, WidthMM, HeightMM int
}

// OrderDelivery — доставка заказа. Куда — из полей формы по ролям, как их
// получил Quote при оформлении.
type OrderDelivery struct {
	MethodID int64
	Name     string
	Handler  string // fixed, pickup или «<плагин>/<код>» — какой выбрал покупатель, даже если способ потом сменили
	Price    int64  // взято с покупателя
	StoreID  int64  // склад самовывоза; 0 — нет
	// Settings — настройки способа сейчас, только если Handler — обработчик
	// этого плагина и у способа он же; способ удалили или сменили ему
	// службу — nil.
	Settings map[string]string

	Place       Place  // поле с ролью «Местоположение»; ID 0 — не было или удалено из справочника
	Zip         string // поле с ролью «Индекс»
	Address     string // поле с ролью «Адрес»
	PickupPoint string // поле с ролью «Пункт выдачи»
}

// OrderPayment — способ оплаты заказа.
type OrderPayment struct {
	MethodID int64
	Name     string
	Handler  string // manual или «<плагин>/<код>»
}
